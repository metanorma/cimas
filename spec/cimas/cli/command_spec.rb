      expect(command.commit_message).to eq("Some commit message\n\nrequest-checks: true")
    end

    it "don't modify message if request-checks: is passed" do
      command = Cimas::Cli::Command.new(options("Some commit message\n\nrequest-checks: false"))

      expect(command.commit_message).to eq("Some commit message\n\nrequest-checks: false")
