  describe "apply_patches" do
    let(:tmp_root) { Dir.mktmpdir("cimas-patches-spec") }
    let(:repo_name) { "metanorma-cli" }
    let(:repo_dir) { File.join(tmp_root, repo_name) }
    let(:gemspec_path) { File.join(repo_dir, "foo.gemspec") }
    let(:git_repo) { Git.init(repo_dir) }

    before do
      FileUtils.mkdir_p(repo_dir)
      File.write(gemspec_path, <<~GEMSPEC)
        Gem::Specification.new do |spec|
          spec.name = "foo"
          spec.required_ruby_version = Gem::Requirement.new(">= 2.7.0")
        end
      GEMSPEC
    end

    after { FileUtils.rm_rf(tmp_root) }

    def build_command(patches_block)
      config_path = File.join(tmp_root, "cimas.yml")
      File.write(config_path, YAML.dump(
        "repositories" => {
          repo_name => {
            "remote" => "ssh://git@github.com/metanorma/#{repo_name}",
            "branch" => "main",
            "files" => {},
          },
        },
        "groups" => {
          "processor" => [repo_name],
        },
        "patches" => patches_block,
      ))

      Cimas::Cli::Command.new(
        "config_file_path" => Pathname.new(config_path),
        "repos_path" => Pathname.new(tmp_root),
      )
    end

    it "rewrites matching lines without prepending the auto-generated header" do
      command = build_command(
        "ruby_version" => {
          "files" => ["*.gemspec"],
          "find" => 'spec\.required_ruby_version\s*=.*',
          "replace" => 'spec.required_ruby_version = Gem::Requirement.new(">= 3.1.0")',
          "groups" => ["processor"],
        },
      )

      command.apply_patches(repo_name, repo_dir, git_repo)
      content = File.read(gemspec_path)

      expect(content).to include('>= 3.1.0')
      expect(content).not_to include('>= 2.7.0')
      expect(content).not_to include('Auto-generated by Cimas')
    end

    it "stages the patched file in the git index under its repo-relative path" do
      command = build_command(
        "ruby_version" => {
          "files" => ["*.gemspec"],
          "find" => 'spec\.required_ruby_version\s*=.*',
          "replace" => 'spec.required_ruby_version = Gem::Requirement.new(">= 3.1.0")',
          "groups" => ["processor"],
        },
      )

      command.apply_patches(repo_name, repo_dir, git_repo)

      # ls-files = the index itself (status.* compares against HEAD, which a
      # freshly-init'd repo does not have).
      expect(git_repo.ls_files).to include("foo.gemspec")
    end

    it "warns and leaves the file untouched when the find pattern does not match" do
      command = build_command(
        "ruby_version" => {
          "files" => ["*.gemspec"],
          "find" => 'this_will_never_match',
          "replace" => 'irrelevant',
          "groups" => ["processor"],
        },
      )

      expect { command.apply_patches(repo_name, repo_dir, git_repo) }
        .to output(/pattern not present in file/).to_stdout

      expect(File.read(gemspec_path)).to include('>= 2.7.0')
    end

    it "warns when the glob matches no files" do
      command = build_command(
        "nonexistent" => {
          "files" => ["*.nope"],
          "find" => 'foo',
          "replace" => 'bar',
          "groups" => ["processor"],
        },
      )

      expect { command.apply_patches(repo_name, repo_dir, git_repo) }
        .to output(/no files matched glob/).to_stdout
    end

    it "skips repos that are not in any of the patch's groups" do
      command = build_command(
        "ruby_version" => {
          "files" => ["*.gemspec"],
          "find" => 'spec\.required_ruby_version\s*=.*',
          "replace" => 'spec.required_ruby_version = Gem::Requirement.new(">= 3.1.0")',
          "groups" => ["model"],
        },
      )

      command.apply_patches(repo_name, repo_dir, git_repo)
      expect(File.read(gemspec_path)).to include('>= 2.7.0')
    end

    it "does not write the file in dry-run mode" do
      config_path = File.join(tmp_root, "cimas.yml")
      File.write(config_path, YAML.dump(
        "repositories" => {
          repo_name => {
            "remote" => "ssh://git@github.com/metanorma/#{repo_name}",
            "branch" => "main",
            "files" => {},
          },
        },
        "groups" => { "processor" => [repo_name] },
        "patches" => {
          "ruby_version" => {
            "files" => ["*.gemspec"],
            "find" => 'spec\.required_ruby_version\s*=.*',
            "replace" => 'spec.required_ruby_version = Gem::Requirement.new(">= 3.1.0")',
            "groups" => ["processor"],
          },
        },
      ))

      command = Cimas::Cli::Command.new(
        "config_file_path" => Pathname.new(config_path),
        "repos_path" => Pathname.new(tmp_root),
        "dry_run" => true,
      )

      command.apply_patches(repo_name, repo_dir, git_repo)
      expect(File.read(gemspec_path)).to include('>= 2.7.0')
      expect(git_repo.ls_files).to be_empty
    end

    it "is a no-op when the config has no patches: block" do
      command = build_command(nil)
      expect { command.apply_patches(repo_name, repo_dir, git_repo) }
        .not_to raise_error
      expect(File.read(gemspec_path)).to include('>= 2.7.0')
    end
  end

  describe "resolve_source (metanorma/ci#347 Option B — visibility-conditional docker.yml)" do
    let(:repo) do
      Cimas::Repository.new(
        "mn-samples-bsi",
        "remote" => "ssh://git@github.com/metanorma/mn-samples-bsi",
        "branch" => "main",
        "files" => {},
      )
    end

    let(:command) { Cimas::Cli::Command.new(options("msg")) }

    it "returns a String source unchanged (legacy path stays the fast path)" do
      expect(command.resolve_source("gh-actions/samples/public-docker.yml", repo))
        .to eq("gh-actions/samples/public-docker.yml")
    end

    context "with a visibility-conditional Hash source" do
      let(:source) do
        {
          "if_public" => "gh-actions/samples/public-docker.yml",
          "if_private" => "gh-actions/samples/private-docker.yml.erb",
        }
      end

      it "picks the private template when the repo is private on GitHub" do
        allow(command).to receive(:repo_visibility_private?).with(repo).and_return(true)
        expect(command.resolve_source(source, repo))
          .to eq("gh-actions/samples/private-docker.yml.erb")
      end

      it "picks the public template when the repo is public on GitHub" do
        allow(command).to receive(:repo_visibility_private?).with(repo).and_return(false)
        expect(command.resolve_source(source, repo))
          .to eq("gh-actions/samples/public-docker.yml")
      end
    end

    it "raises when the Hash source is missing either required key" do
      allow(command).to receive(:repo_visibility_private?).with(repo).and_return(false)
      expect { command.resolve_source({ "if_public" => "x" }, repo) }
        .to raise_error(/visibility-conditional source needs/)
      expect { command.resolve_source({ "if_private" => "x" }, repo) }
        .to raise_error(/visibility-conditional source needs/)
    end

    it "caches the visibility lookup across multiple resolves on the same repo" do
      call_count = 0
      allow(command).to receive(:fetch_repo_visibility) do
        call_count += 1
        true
      end
      source = {
        "if_public" => "gh-actions/samples/public-docker.yml",
        "if_private" => "gh-actions/samples/private-docker.yml.erb",
      }
      3.times { command.resolve_source(source, repo) }
      expect(call_count).to eq(1)
    end
  end

