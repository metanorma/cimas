  describe "scope guard for remote-mutating commands" do
    # push validates its required flags eagerly at execute; specs that
    # get past validation must supply them.
    PUSH_REQUIRED_OPTIONS = {
      "push_to_branch" => "wave-branch",
      "commit_message" => "msg",
    }.freeze

    let(:tmp_root) { Dir.mktmpdir("cimas-scope-spec") }

    after { FileUtils.rm_rf(tmp_root) }

    def build_command(with_groups: false, config_groups: nil, settings_groups: nil, extra: {})
      config = {
        "repositories" => {
          "repo-a" => { "remote" => "git@github.com:org/repo-a.git", "branch" => "main", "files" => {} },
          "repo-b" => { "remote" => "git@github.com:org/repo-b.git", "branch" => "main", "files" => {} },
        },
      }
      config["groups"] = config_groups if config_groups
      config["groups"] ||= { "data" => %w[repo-a repo-b] } if with_groups
      config["settings"] = { "groups" => settings_groups } if settings_groups
      config_path = File.join(tmp_root, "cimas.yml")
      File.write(config_path, YAML.dump(config))

      Cimas::Cli::Command.new({
        "config_file_path" => Pathname.new(config_path),
        "repos_path" => Pathname.new(tmp_root),
      }.merge(extra))
    end

    it "refuses push without -g because it would target every repository" do
      command = build_command

      expect { command.execute("push") }
        .to raise_error(OptionParser::MissingArgument, /would target all 2 repositories/)
    end

    it "refuses open-prs without -g before touching the GitHub API" do
      command = build_command

      expect { command.execute("open-prs") }
        .to raise_error(OptionParser::MissingArgument, /no -g given/)
    end

    it "refuses cleanup-merged-prs without -g" do
      command = build_command

      expect { command.execute("cleanup-merged-prs") }
        .to raise_error(OptionParser::MissingArgument, /cleanup-merged-prs: no -g given/)
    end

    it "refuses cleanup-closed-prs without -g" do
      command = build_command

      expect { command.execute("cleanup-closed-prs") }
        .to raise_error(OptionParser::MissingArgument, /cleanup-closed-prs: no -g given/)
    end

    it "refuses for-each without -g (arbitrary shell has push-scale blast radius)" do
      command = build_command

      expect { command.execute("for-each") }
        .to raise_error(OptionParser::MissingArgument, /for-each: no -g given/)
    end

    it "refuses an empty -g (e.g. `-g ''`) instead of silently doing nothing" do
      command = build_command(with_groups: true, extra: { "groups" => [] })

      expect { command.execute("push") }
        .to raise_error(OptionParser::InvalidArgument, /-g given but empty/)
    end

    it "refuses a -g group that resolves to zero repositories" do
      command = build_command(
        with_groups: true,
        config_groups: { "empty" => [] },
        extra: { "groups" => ["empty"] },
      )

      expect { command.execute("push") }
        .to raise_error(OptionParser::InvalidArgument, /resolves to 0 repositories/)
    end

    it "leaves cleanup-orphan-files unguarded without --push-after (local-only)" do
      command = build_command

      expect { command.execute("cleanup-orphan-files") }
        .not_to raise_error
    end

    it "guards cleanup-orphan-files when --push-after makes it remote-mutating" do
      command = build_command(extra: { "cleanup_push_after" => true })

      expect { command.execute("cleanup-orphan-files") }
        .to raise_error(OptionParser::MissingArgument, /cleanup-orphan-files: no -g given/)
    end

    it "leaves local-only commands unguarded without -g" do
      command = build_command

      expect { command.execute("diff") }
        .not_to raise_error
    end

    it "treats groups from cimas.yml settings as deliberate scope (no CLI -g needed)" do
      command = build_command(
        with_groups: true,
        settings_groups: ["data"],
        extra: PUSH_REQUIRED_OPTIONS,
      )

      expect { command.execute("push") }
        .to output(/Scope for push: 2 repo\(s\): repo-a, repo-b/).to_stdout
    end

    it "runs push scoped to a group and announces the scope" do
      command = build_command(
        with_groups: true,
        extra: { "groups" => ["data"] }.merge(PUSH_REQUIRED_OPTIONS),
      )

      expect { command.execute("push") }
        .to output(/Scope for push: 2 repo\(s\): repo-a, repo-b/).to_stdout
    end

    it "allows a single repo name as the group" do
      command = build_command(
        with_groups: true,
        extra: { "groups" => ["repo-a"] }.merge(PUSH_REQUIRED_OPTIONS),
      )

      expect { command.execute("push") }
        .to output(/Scope for push: 1 repo\(s\): repo-a/).to_stdout
    end

    it "announces the scope for cleanup commands too (uniform blast-radius line)" do
      command = build_command(with_groups: true, extra: { "groups" => ["repo-a"] })

      # cleanup-closed-prs requires no other flags: it announces, then
      # fails at the GitHub client — proving the announcement happens
      # before any GitHub interaction.
      expect { command.execute("cleanup-closed-prs") }
        .to output(/Scope for cleanup-closed-prs: 1 repo\(s\): repo-a/).to_stdout
        .and raise_error(/GITHUB_TOKEN/)
    end

    it "collapses the scope list past the announcement limit" do
      repos = (1..31).each_with_object({}) do |i, acc|
        acc["repo-#{i}"] = { "remote" => "git@github.com:org/repo-#{i}.git",
                             "branch" => "main", "files" => {} }
      end
      config = { "repositories" => repos }
      config_path = File.join(tmp_root, "cimas.yml")
      File.write(config_path, YAML.dump(config))

      command = Cimas::Cli::Command.new({
        "config_file_path" => Pathname.new(config_path),
        "repos_path" => Pathname.new(tmp_root),
        "groups" => ["all"],
      }.merge(PUSH_REQUIRED_OPTIONS))

      expect { command.execute("push") }
        .to output(/Scope for push: 31 repo\(s\): \(list omitted, >30 repos\)/).to_stdout
    end
  end

